#!/usr/bin/env python3
"""Assemble a hoike signer config: template + generated issuer identity.

hoike's dogtag-sync source has no issuer-cert fallback (only the CRL source
does), so a signer config needs `issuer_name_der_b64` / `issuer_key_bytes_b64`
for CertID computation (RFC 6960 §4.1.1). Those bytes are deployment-specific,
generated by scripts/pki/gen-ca-identity.py after the CA exists. This script
merges the matching identity block into a signer template and prints the
final config — typically to /run/cert-revocation-lab/hoike-<h>-signer.toml,
which hoike-compose.yml mounts.

Usage:
    assemble-signer-config.py --template configs/hoike/pq-config.toml \
        --identity configs/hoike/ca-identity.toml --label pq-iot \
        > /run/cert-revocation-lab/hoike-pq-signer.toml

Assisted-by: Codex (Codex.ai/code)
"""

from __future__ import annotations

import argparse
import sys
import tomllib
from pathlib import Path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--template", required=True, type=Path)
    parser.add_argument("--identity", required=True, type=Path)
    parser.add_argument("--label", required=True)
    args = parser.parse_args()

    identity = tomllib.loads(args.identity.read_text())
    block = next(
        (b for b in identity.get("ca", []) if b.get("label") == args.label), None
    )
    if block is None:
        sys.exit(f"error: no [[ca]] block labelled '{args.label}' in {args.identity}")

    name_b64 = block.get("issuer_name_der_b64")
    key_b64 = block.get("issuer_key_bytes_b64")
    if not name_b64 or not key_b64:
        sys.exit(
            f"error: identity block '{args.label}' lacks issuer DN/key bytes — "
            "regenerate with scripts/pki/gen-ca-identity.py"
        )

    # The signer templates carry exactly one [[ca]] block; inject the identity
    # fields directly under it (before any [ca.*] subtable) so they belong to
    # the ca table itself.
    text = args.template.read_text()
    marker = "[[ca]]"
    index = text.find(marker)
    if index == -1:
        sys.exit(f"error: no [[ca]] block in {args.template}")
    insert_at = text.find("\n", index) + 1
    injection = (
        f"issuer_name_der_b64  = \"{name_b64}\"\n"
        f"issuer_key_bytes_b64 = \"{key_b64}\"\n"
    )
    sys.stdout.write(text[:insert_at] + injection + text[insert_at:])


if __name__ == "__main__":
    main()
